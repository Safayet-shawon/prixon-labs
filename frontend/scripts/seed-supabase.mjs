// Seeds Supabase from src/data.js (the single source of truth).
//   node scripts/seed-supabase.mjs         -> upsert through the REST API
//   node scripts/seed-supabase.mjs --sql   -> write ../supabase/seed.sql
// Needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY for the REST mode.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { seedProjects, seedServices } from '../api/_lib/seed.js'

const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const arr = (a) => q(a.join('|'))

if (process.argv.includes('--sql')) {
  const lines = ['-- Generated by frontend/scripts/seed-supabase.mjs — do not edit by hand.', '']
  seedServices.forEach((s, i) => {
    lines.push(
      `insert into public.services (id, title, description, category, sort_order) values (${q(s.id)}, ${q(s.title)}, ${q(s.description)}, ${q(s.category)}, ${i + 1})`,
      `  on conflict (id) do update set title = excluded.title, description = excluded.description, category = excluded.category, sort_order = excluded.sort_order;`,
    )
  })
  lines.push('')
  seedProjects.forEach((p, i) => {
    lines.push(
      `insert into public.projects (slug, name, type, year, summary, intro, challenge, approach, outcome, scope, visual_theme, visual_note, sort_order) values (${[p.slug, p.name, p.type, p.year, p.summary, p.intro, p.challenge, p.approach, p.outcome].map(q).join(', ')}, ${arr(p.scope)}, ${q(p.visualTheme)}, ${q(p.visualNote)}, ${i + 1})`,
      `  on conflict (slug) do update set name = excluded.name, type = excluded.type, year = excluded.year, summary = excluded.summary, intro = excluded.intro, challenge = excluded.challenge, approach = excluded.approach, outcome = excluded.outcome, scope = excluded.scope, visual_theme = excluded.visual_theme, visual_note = excluded.visual_note, sort_order = excluded.sort_order;`,
    )
  })
  const target = fileURLToPath(new URL('../../supabase/seed.sql', import.meta.url))
  writeFileSync(target, lines.join('\n') + '\n')
  console.log(`Wrote ${target}`)
} else {
  const url = (process.env.SUPABASE_URL || '').replace(/\/+$/, '')
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) {
    console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY first.')
    process.exit(1)
  }
  const upsert = async (table, conflict, rows) => {
    const response = await fetch(`${url}/rest/v1/${table}?on_conflict=${conflict}`, {
      method: 'POST',
      headers: {
        apikey: key,
        Authorization: `Bearer ${key}`,
        'Content-Type': 'application/json',
        Prefer: 'resolution=merge-duplicates,return=minimal',
      },
      body: JSON.stringify(rows),
    })
    if (!response.ok) throw new Error(`${table}: ${response.status} ${await response.text()}`)
    console.log(`Seeded ${rows.length} rows into ${table}`)
  }
  await upsert(
    'services',
    'id',
    seedServices.map((s, i) => ({ ...s, sort_order: i + 1 })),
  )
  await upsert(
    'projects',
    'slug',
    seedProjects.map((p, i) => ({
      slug: p.slug,
      name: p.name,
      type: p.type,
      year: p.year,
      summary: p.summary,
      intro: p.intro,
      challenge: p.challenge,
      approach: p.approach,
      outcome: p.outcome,
      scope: p.scope.join('|'),
      visual_theme: p.visualTheme,
      visual_note: p.visualNote,
      sort_order: i + 1,
    })),
  )
}
